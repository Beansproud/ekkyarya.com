  if (l === "Fan art") return t("tag.fan");
  if (l === "Client work") return t("tag.clientWork");
  let m = l.match(/^Client: (.+)$/); if (m) return t("tag.client", { name: m[1] });
  m = l.match(/^Competition entry: (.+)$/); if (m) return t("tag.entry", { name: m[1] });
